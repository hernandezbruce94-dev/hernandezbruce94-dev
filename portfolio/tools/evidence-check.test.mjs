import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { validate, isoTime } from './evidence-check.mjs';
const sample = JSON.parse(readFileSync(new URL('./fixtures/valid.json', import.meta.url), 'utf8'));
const now = Date.parse('2026-10-29T12:00:00Z');
const copy = () => structuredClone(sample);
test('valid synthetic record passes without establishing effectiveness', () => assert.deepEqual(validate(sample, now), []));
test('missing owner is rejected', () => { const x=copy();x.records[0].owner=' ';assert.ok(validate(x,now).some(e=>e.includes('missing owner'))); });
test('duplicate IDs with whitespace are rejected', () => {const x=copy();x.records.push({...x.records[0],id:' SYN-001 '});assert.ok(validate(x,now).some(e=>e.includes('duplicate')));});
test('impossible date rejected', () => assert.equal(isoTime('2026-02-30T12:00:00Z'), null));
test('timezone-free timestamp rejected', () => assert.equal(isoTime('2026-10-29T12:00:00'), null));
test('future observation rejected', () => {const x=copy();x.records[0].tested_at='2026-10-30T12:00:00Z';assert.ok(validate(x,now).some(e=>e.includes('future')));});
test('overdue review rejected', () => {const x=copy();x.records[0].review_due='2026-10-28T13:00:00Z';assert.ok(validate(x,now).some(e=>e.includes('overdue')));});
test('review before observation rejected', () => {const x=copy();x.records[0].review_due='2026-10-27T12:00:00Z';assert.ok(validate(x,now).some(e=>e.includes('predates')));});
test('empty or malformed roots rejected', () => {for(const x of [null,[],{}, {schema_version:1,records:[]}])assert.ok(validate(x,now).length);});
test('unknown result and kind rejected', () => {const x=copy();x.records[0].result='certified';x.records[0].evidence_kind='assumed';assert.equal(validate(x,now).length,2);});
test('null record rejected without crash', () => assert.ok(validate({schema_version:1,records:[null]},now).length));
test('CLI returns 0 valid, 1 findings, 2 input/usage errors', () => {
 const tool=fileURLToPath(new URL('./evidence-check.mjs',import.meta.url));
 const run=(...args)=>spawnSync(process.execPath,[tool,...args],{encoding:'utf8'});
 const fixture=(n)=>fileURLToPath(new URL('./fixtures/'+n+'.json',import.meta.url));
 assert.equal(run(fixture('valid'),'--now','2026-10-29T12:00:00Z').status,0);
 assert.equal(run(fixture('invalid'),'--now','2026-10-29T12:00:00Z').status,1);
 assert.equal(run().status,2);
 assert.equal(run(fixture('valid'),'--now','not-a-date').status,2);
 assert.equal(run(fixture('missing')).status,2);
});
